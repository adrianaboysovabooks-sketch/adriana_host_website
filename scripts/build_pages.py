"""Rebuild the five supplied-reference pages as portable static HTML.

Edit content/pages.json or links.json for copy and verified article destinations.
Shared header/footer and styles come from index.html; no runtime framework is used.
"""
import html,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
D=json.loads((ROOT/'content/pages.json').read_text())
LINKS=json.loads((ROOT/'content/links.json').read_text())
esc=lambda value:html.escape(str(value),quote=True)

def paragraph(text,cls=''):
 return f'<p{f" class={chr(34)}{cls}{chr(34)}" if cls else ""}>{esc(text)}</p>'
def paragraphs(values):return '\n'.join(paragraph(p) for p in values)
def image(name,alt,cls='',eager=False):
 from PIL import Image
 try:w,h=Image.open(ROOT/'assets/images'/name).size
 except OSError:
  asset=next(a for a in json.loads((ROOT/'content/assets.json').read_text()) if a['file']=='assets/images/'+name)
  w,h=asset['size']
 return f'<img class="{cls}" src="assets/images/{name}" alt="{esc(alt)}" width="{w}" height="{h}" loading="{"eager" if eager else "lazy"}" decoding="async">'
def linked(label,url):return f'<a href="{esc(url)}">{esc(label)}</a>'
def supplied_link(start):
 return next(linked(l['label'],l['url']) for l in LINKS if l['label'].startswith(start))
def points(values):
 rows=[]
 for text in values:
  before,sep,after=text.partition(':')
  rows.append('<li>'+('<strong>'+esc(before)+':</strong>'+esc(after) if sep else esc(text))+'</li>')
 return '<ul class="reason-list">'+''.join(rows)+'</ul>'
def quote(text,cls=''):return f'<blockquote class="book-quote {cls}"><p>{esc(text)}</p></blockquote>'
def articles(items):return '<section class="article-links"><h2>Odkazy na články</h2><ul>'+''.join('<li>'+item+'</li>' for item in items)+'</ul></section>'

home=(ROOT/'index.html').read_text()
NAV={'https://adrianaboysova.wixsite.com/adriana-boysov/o-mne':'o-mne.html','https://adrianaboysova.wixsite.com/adriana-boysov/blank-2':'zachranene-vianoce.html','https://adrianaboysova.wixsite.com/adriana-boysov/blank':'zamatovy-jez.html','https://adrianaboysova.wixsite.com/adriana-boysov/blank-1':'mimoza.html'}
# Replace only navigation's events link; RSVP remains on its verified original service.
for old,new in sorted(NAV.items(),key=lambda item:len(item[0]),reverse=True):home=home.replace('href="'+old+'"','href="'+new+'"')
nav_start=home.index('<nav id="main-nav"');nav_end=home.index('</nav>',nav_start)
nav=home[nav_start:nav_end].replace('https://adrianaboysova.wixsite.com/adriana-boysov/event-list','novinky.html')
home=home[:nav_start]+nav+home[nav_end:]
(ROOT/'index.html').write_text(home)
head=home[:home.index('<body>')]
header=re.search(r'<header class="site-header">.*?</header>',home,re.S).group()
footer=re.search(r'<footer>.*?</footer>',home,re.S).group()
def page(filename,title,description,body,cls=''):
 page_head=re.sub(r'<title>.*?</title>',f'<title>{esc(title)} — Adriana Boysová</title>',head)
 for key in ['name="description"','property="og:description"']:
  page_head=re.sub('(<meta '+key+' content=")[^"]*',lambda m:m[1]+esc(description),page_head)
 page_head=re.sub(r'(<meta property="og:title" content=")[^"]*',lambda m:m[1]+esc(title)+' — Adriana Boysová',page_head)
 page_header=header.replace(' aria-current="page"','').replace(f'href="{filename}"',f'href="{filename}" aria-current="page"')
 source=page_head+f'''<body class="detail-page {cls}">
<!-- Generated by scripts/build_pages.py; copy and source links are in content/pages.json and content/links.json. -->
<a class="skip-link" href="#main">Preskočiť na obsah</a>
{page_header}
<main id="main">{body}</main>
{footer}
</body>
</html>
'''
 (ROOT/filename).write_text(source)

a=D['about']
about=f'''<section class="about-intro inner">
{image('author-library.webp','Adriana Boysová medzi knižničnými regálmi','library-portrait',True)}
<div class="about-introduction"><h1>O autorke</h1>{paragraph(a['biography'])}</div></section>
<section class="writing-section"><div class="inner"><h2>O písaní</h2>{paragraph(a['writing'][0],'writing-opening')}
<div class="writing-grid"><figure>{image('author-bookshop.webp','Adriana Boysová so svojou knihou v kníhkupectve')}<figcaption>Príbeh môjho debutu</figcaption></figure><div>{paragraph(a['writing'][1])}<p class="booklover" aria-hidden="true">Booklover ✳ Booklover ✳</p></div></div>
<div class="resources-grid"><div><h2>Knihy</h2>{paragraph(a['books'][0])}<ul class="publisher-list"><li>Zachránené Vianoce - vydavateľstvo {supplied_link('Albatrosmedia')}</li><li>Zamatový jež - vydavateľsvo {supplied_link('Lindeni')}</li><li>{esc(a['books'][3])}</li></ul>{image('mimosa-branch.avif','','mimosa-sprig')}</div><figure>{image('book-stack.webp','Stoh kníh na stole')}<figcaption>{supplied_link('Prečo, ako a kde píšem')}</figcaption></figure></div>
</div></section>'''
page('o-mne.html','O mne','O autorke Adriane Boysovej, jej písaní, knihách a príbehoch.',about,'about-page')

c=D['christmas']
christmas=f'''<article class="book-page inner christmas-page"><div class="christmas-opening"><div><h1>Zachránené<br>Vianoce</h1>{paragraph(c['intro'])}{quote(c['quote'])}</div>{image('christmas-story.webp','Ilustrácia dievčatka v žltej čiapke s mačkou v zasneženom meste','story-illustration',True)}</div>
<div class="book-detail-grid"><div class="book-photos">{image('christmas-books.webp','Kniha Zachránené Vianoce na stole')}{image('christmas-launch.webp','Adriana Boysová a hostia pri uvedení knihy Zachránené Vianoce')}</div><div>{paragraph(c['tagline'],'book-tagline')}<section class="story-card">{paragraph(c['description'])}<h2>Povedali o knihe:</h2><blockquote>{paragraphs(c['review'])}</blockquote></section><p class="book-signature" aria-hidden="true">Zachránené Vianoce</p></div></div>
<section class="book-reasons"><h2>Prečo si túto knihu prečítať</h2>{points(c['reasons'])}</section>{image('christmas-dream.avif','Ilustrácia dievčatka, ktoré sníva pod mesiacom medzi oblakmi','dream-illustration')}</article>'''
page('zachranene-vianoce.html','Zachránené Vianoce','Čarovný a láskavý príbeh Adriany Boysovej o nádeji, priateľstve a vianočnom zázraku.',christmas)

z=D['hedgehog']
hedgehog=f'''<article class="book-page inner"><h1>Zamatový jež</h1><div class="book-opening"><div>{paragraph(z['intro'])}{paragraph(z['tagline'],'book-tagline')}</div><div class="opening-quote">{quote(z['quote'])}</div></div>
<div class="book-detail-grid"><figure>{image('zamatovy-jez-detail.webp','Kniha Zamatový jež pri domácom čítaní','book-detail-photo',True)}<figcaption>{quote(z['closing_quote'])}</figcaption></figure><section class="story-card">{paragraphs(z['description'])}</section></div>
<section class="book-reasons"><h2>Prečo si román všimnúť</h2>{points(z['reasons'])}</section>
{articles([supplied_link('Trinásť'),supplied_link('Autorka Zamatového'),supplied_link('Klub knihomolov'),supplied_link('Žijem v krajine')])}</article>'''
page('zamatovy-jez.html','Zamatový jež','Spoločenský román Adriany Boysovej o dospievaní, vine, odpustení a hľadaní identity.',hedgehog)

m=D['mimosa']
mimosa=f'''<article class="book-page inner mimosa-page"><div class="mimosa-columns"><div><h1>Mimóza</h1>{paragraph(m['intro'])}<figure class="mimosa-cover">{image('mimoza.webp','Obálka knihy Mimóza od Adriany Boysovej','',True)}</figure><section class="mimosa-review"><h2>{esc(m['review_title'])}</h2>{paragraph(m['review'])}</section></div><div class="mimosa-right">{quote(m['quote'])}{image('mimosa-branch.avif','','mimosa-sprig')}<section class="story-card">{paragraph(m['description'])}</section></div></div>
<section class="book-reasons"><h2>Prečo si knihu všimnúť</h2>{points(m['reasons'])}<h3>{esc(m['reader_title'])}</h3>{points(m['reader_reasons'])}</section>
{articles([esc(m['unlinked_article']), 'Denník Pravda: '+supplied_link('Mimóza:'),'Púchovské noviny: '+supplied_link('Adriana Boysová:')])}</article>'''
page('mimoza.html','Mimóza','Osemnásť poviedok Adriany Boysovej o láske i neláske a príbehoch zo života.',mimosa)

club='https://adrianaboysova.wixsite.com/adriana-boysov/event-list'
news=f'''<section class="news-page inner"><h1>Novinky</h1><article class="event-card">{image('book-club-reference.webp','Otvorená kniha počas čítania','',True)}<div><h2>Knižný klub</h2><p>Podľa dohody&nbsp; / &nbsp;Online</p><p>{linked('Viac informácií',club)}</p><a class="solid-button" href="{club}" aria-label="RSVP — pôvodná stránka knižného klubu">RSVP</a></div></article></section>'''
page('novinky.html','Novinky','Knižný klub a stretnutia s autorkou Adrianou Boysovou.',news)
print('Built o-mne.html, zachranene-vianoce.html, zamatovy-jez.html, mimoza.html and novinky.html; local navigation updated.')
